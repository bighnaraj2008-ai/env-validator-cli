"""Generate a structured Markdown test execution report for env-validator-cli."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
from pathlib import Path
import subprocess
import sys

REPO_ROOT = Path(__file__).resolve().parent.parent


def run_and_generate_markdown(output_path: Path | None = None) -> str:
    """Execute pytest and render a comprehensive Markdown test report."""
    cmd = [
        sys.executable,
        "-m",
        "pytest",
        "tests",
        "-v",
        "--tb=short",
        "-p",
        "no:cacheprovider",
    ]
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)

    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    status = "PASSED" if proc.returncode == 0 else "FAILED"

    report_lines = [
        "# Test Execution Report",
        "",
        "- **Repository**: `env-validator-cli`",
        f"- **Execution Timestamp**: {timestamp}",
        f"- **Status**: `{status}`",
        f"- **Exit Code**: {proc.returncode}",
        "",
        "## Pytest Output Summary",
        "",
        "```text",
        proc.stdout.strip(),
        "```",
        "",
        "---",
        "*Report auto-generated by `scripts/generate_test_report.py`.*",
    ]
    content = "\n".join(report_lines) + "\n"
    if output_path:
        output_path.write_text(content, encoding="utf-8")
    return content


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate Markdown test report.")
    parser.add_argument("--output", type=Path, default=None, help="Optional output path")
    args = parser.parse_args()
    report = run_and_generate_markdown(args.output)
    if not args.output:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
